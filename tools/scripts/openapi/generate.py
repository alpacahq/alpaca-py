def _run(command: list[str]) -> None:
    """Run a codegen tool, surfacing its output only when it fails."""
    try:
        subprocess.run(
            command, check=True, cwd=REPOSITORY_ROOT, capture_output=True, text=True
        )
    except subprocess.CalledProcessError as error:
        sys.stderr.write(error.stdout or "")
        sys.stderr.write(error.stderr or "")
        raise


def _load_surface_file(path: Path, allowed: frozenset[str]) -> dict:
    document = json.loads(path.read_text())
    if not isinstance(document, dict):
        raise ValueError(f"{path.name} must be a JSON object")
    unknown = sorted(set(document) - allowed)
    if unknown:
        raise ValueError(f"{path.name} has unsupported keys: {', '.join(unknown)}")
    return document


def load_surface(path: Path) -> dict:
    """Load and merge surface settings from a directory or a single JSON file.

    Production surfaces live under ``tools/openapi/surfaces/<name>/`` as three
    files (``manifest.json``, ``sdk.json``, ``patches.json``). Tests may pass a
    single combined JSON file with the same keys.
    """
    if path.is_dir():
        merged: dict = {}
        for name in SURFACE_FILES:
            file_path = path / name
            if not file_path.is_file():
                raise ValueError(f"surface directory is missing {name}: {path}")
            section = _load_surface_file(file_path, FILE_KEYS[name])
            overlap = sorted(set(merged) & set(section))
            if overlap:
                raise ValueError(
                    f"duplicate surface keys across files: {', '.join(overlap)}"
                )
            merged.update(section)
        return merged

    if path.is_file():
        return _load_surface_file(path, SURFACE_KEYS)

    raise ValueError(f"surface path does not exist: {path}")


def _format_patch_path(path: list[str]) -> str:
    return "/".join(path)


def apply_spec_patches(document: dict, patches: list[dict] | None) -> dict:
    """Return a deep copy of ``document`` with maintainer patches applied.

    Patches keep the checked-in download faithful to Alpaca while letting generation
    work around OpenAPI Generator gaps (for example OpenAPI 3.1 ``type: null``).

    Every patch must still point at a live leaf and must change that leaf. Upstream
    removals or fixes therefore fail generation until the dead entry is deleted from
    ``patches.json``.

    ``"op": "add"`` instead inserts a key the specification is missing (for example
    a property the API returns but the spec omits). Its parent must exist and the key
    must not, so generation fails once upstream adds it.
    """
    patched = copy.deepcopy(document)
    for index, patch in enumerate(patches or []):
        if not isinstance(patch, dict):
            raise ValueError(f"specPatches[{index}] must be an object")
        op = patch.get("op", "replace")
        if op not in {"replace", "add"}:
            raise ValueError(f"specPatches[{index}] op must be 'replace' or 'add'")
        path = patch.get("path")
        if (
            not isinstance(path, list)
            or not path
            or not all(isinstance(part, str) and part for part in path)
        ):
            raise ValueError(
                f"specPatches[{index}] requires a non-empty path of non-empty strings"
            )
        if "value" not in patch:
            raise ValueError(f"specPatches[{index}] requires a value")
        reason = patch.get("reason")
        if not isinstance(reason, str) or not reason.strip():
            raise ValueError(f"specPatches[{index}] requires a non-empty reason")

        cursor: Any = patched
        for depth, part in enumerate(path[:-1]):
            if not isinstance(cursor, dict) or part not in cursor:
                raise ValueError(
                    "specPatches path does not exist: "
                    f"{_format_patch_path(path[: depth + 1])} "
                    f"(from {_format_patch_path(path)}; {reason})"
                )
            cursor = cursor[part]
        leaf = path[-1]
        if op == "add":
            if not isinstance(cursor, dict):
                raise ValueError(
                    "specPatches path does not exist: "
                    f"{_format_patch_path(path[:-1])} ({reason})"
                )
            if leaf in cursor:
                raise ValueError(
                    "specPatches add target already exists upstream "
                    f"(remove the dead entry): {_format_patch_path(path)} ({reason})"
                )
            cursor[leaf] = copy.deepcopy(patch["value"])
            continue
        if not isinstance(cursor, dict) or leaf not in cursor:
            raise ValueError(
                "specPatches path does not exist: "
                f"{_format_patch_path(path)} ({reason})"
            )
        current = cursor[leaf]
        if current == patch["value"]:
            raise ValueError(
                "specPatches entry already has the patched value "
                f"(remove the dead mapping): {_format_patch_path(path)} ({reason})"
            )
        cursor[leaf] = copy.deepcopy(patch["value"])
    return patched


def _run_generator(
    spec: Path, config: Path, output: Path, mappings: dict[str, str]
) -> None:
    if not GENERATOR_CLI.exists():
        raise ToolchainError(
            f"{GENERATOR_CLI} is missing; run `npm ci --ignore-scripts` to install the pinned generator"
        )
    command = [
        str(GENERATOR_CLI),
        "generate",
        "--config",
        str(config),
        "--input-spec",
        str(spec),
        "--output",
        str(output),
    ]
    if mappings:
        command += [
            "--name-mappings",
            ",".join(f"{key}={value}" for key, value in sorted(mappings.items())),
        ]
    _run(command)


def _read_fragments(root: Path) -> list[Fragment]:
    """Collect the fragments emitted by the repository templates.

    Files the stock templates produce, such as the unused HTTP transport, carry no
    fragment marker and are ignored.
    """
    fragments = []
    for path in sorted(root.rglob("*.py")):
        lines = path.read_text().splitlines()
        marker = next(
            (
                index
                for index, line in enumerate(lines)
                if line.startswith(FRAGMENT_MARKER)
            ),
            None,
        )
        if marker is None:
            continue
        metadata = json.loads(lines[marker][len(FRAGMENT_MARKER) :])
        fragments.append(
            Fragment(
                kind=metadata["kind"],
                name=metadata["name"],
                enum_type=metadata["enumType"],
                package=metadata["package"],
                references=tuple(sorted(metadata["references"])),
                imports=tuple(sorted(metadata["imports"])),
                body="\n".join(lines[marker + 1 :]).strip("\n"),
            )
        )
    return fragments


def _schema_descriptions(document: dict) -> dict[str, str]:
    """Return component schema descriptions keyed by schema name.

    OpenAPI Generator collapses newlines in ``{{{description}}}`` to spaces, so the
    assembler re-applies these original strings when writing class docstrings.
    """
    schemas = document.get("components", {}).get("schemas", {})
    return {
        name: description
        for name, schema in schemas.items()
        if isinstance(schema, dict)
        and isinstance(description := schema.get("description"), str)
        and description.strip()
    }


_LEADING_DOCSTRING = re.compile(
    r'\A(?P<indent>[ \t]*)(?P<quote>"""|\'\'\')(?P<body>.*?)(?P=quote)',
    re.DOTALL,
)


_LIST_BULLET = re.compile(r"(?P<indent>[ \t]*)[-*+][ \t]+")


def _rst_list_layout(lines: list[str]) -> list[str]:
    """Lay out Markdown lists the way reStructuredText needs them.

    Sphinx parses docstrings as reStructuredText, which, unlike Markdown, needs a
    blank line between a paragraph and a list, a blank line where a nested list
    returns to its parent, and continuation lines indented to their item's text.
    """
    laid_out: list[str] = []
    bullet_indents: list[int] = []
    text_column: int | None = None
    for line in lines:
        if not line.strip():
            laid_out.append(line)
            continue
        previous_blank = not laid_out or not laid_out[-1].strip()
        bullet = _LIST_BULLET.match(line)
        if bullet:
            bullet_indent = len(bullet.group("indent"))
            starts_list = text_column is None or bullet_indent >= text_column
            leaves_nested = bool(bullet_indents) and bullet_indent < bullet_indents[-1]
            if not previous_blank and (starts_list or leaves_nested):
                laid_out.append("")
            while bullet_indents and bullet_indents[-1] > bullet_indent:
                bullet_indents.pop()
            if not bullet_indents or bullet_indents[-1] < bullet_indent:
                bullet_indents.append(bullet_indent)
            text_column = bullet.end()
            laid_out.append(line)
            continue
        indent = len(line) - len(line.lstrip())
        if text_column is not None and indent < text_column:
            if previous_blank:
                bullet_indents.clear()
                text_column = None
            else:
                line = " " * text_column + line.lstrip()
        laid_out.append(line)
    return laid_out


def _format_docstring(description: str, *, indent: str = "    ") -> str:
    """Render an OpenAPI description as an indented Python class docstring."""
    cleaned = textwrap.dedent(description).strip("\n")
    cleaned = cleaned.replace("\\", "\\\\").replace('"""', '\\"""')
    if not cleaned.strip():
        return f'{indent}"""\n{indent}"""'
    lines = _rst_list_layout([line.rstrip() for line in cleaned.splitlines()])
    body = "\n".join(f"{indent}{line}" if line else "" for line in lines)
    return f'{indent}"""\n{body}\n{indent}"""'


def _with_schema_docstring(fragment: Fragment, description: str) -> Fragment:
    """Replace a fragment's leading docstring with a formatted OpenAPI description."""
    if fragment.kind in {"operations", "union"}:
        return fragment
    docstring = _format_docstring(description)
    match = _LEADING_DOCSTRING.match(fragment.body)
    if match is None:
        leading_stripped = fragment.body.lstrip("\n")
        body = f"{docstring}\n\n{leading_stripped}"
    else:
        body = f"{docstring}{fragment.body[match.end():]}"
    return Fragment(
        kind=fragment.kind,
        name=fragment.name,
        enum_type=fragment.enum_type,
        package=fragment.package,
        references=fragment.references,
        imports=fragment.imports,
        body=body,
    )


def apply_schema_docstrings(
    fragments: Iterable[Fragment], descriptions: dict[str, str]
) -> list[Fragment]:
    """Restore multiline OpenAPI descriptions that the generator flattened."""
    restored = []
    for fragment in fragments:
        description = descriptions.get(fragment.name)
        if description is None:
            restored.append(fragment)
        else:
            restored.append(_with_schema_docstring(fragment, description))
    return restored


def _is_renderable(fragment: Fragment) -> bool:
    """Report whether a fragment is a usable Python declaration body.

    OpenAPI Generator has schema shapes the repository templates do not model, and it
    renders them as fields without a type annotation, which does not parse.
    """
    if fragment.kind == "operations":
        return True
    if fragment.kind == "union":
        return bool(UNION_ALIAS.fullmatch(fragment.body))
    try:
        ast.parse(f"class {fragment.name}(_Base):\n{fragment.body}")
    except SyntaxError:
        return False
    return True


def reject_unsupported_fragments(
    fragments: Iterable[Fragment], manual_schemas: Iterable[str] = ()
) -> None:
    """Fail on schemas the repository templates cannot express yet.

    Such a schema needs either a richer template or an entry in ``manualSchemas`` that
    keeps it hand-written.
    """
    manual = set(manual_schemas)
    unsupported = sorted(
        fragment.name
        for fragment in fragments
        if fragment.name not in manual and not _is_renderable(fragment)
    )
    if unsupported:
        raise ValueError(
            "the templates in tools/openapi/templates/python cannot express these "
            "schemas, so extend them or list the schemas in manualSchemas: "
            + ", ".join(unsupported)
        )


def reject_manual_references(
    fragments: Iterable[Fragment], categories: dict[str, str]
) -> None:
    """Fail when generated code would reference a hand-written schema.

    ``manualSchemas`` keeps a schema out of the generated modules, so the assembler has
    no module to import it from and the annotation would never resolve. Every schema
    that references a hand-written one has to be hand-written too.
    """
    dangling = sorted(
        f"{fragment.name}.{reference}"
        for fragment in fragments
        if categories.get(fragment.name) not in (None, "manual")
        for reference in fragment.references
        if categories.get(reference) == "manual"
    )
    if dangling:
        raise ValueError(
            "these generated schemas reference manually owned schemas, so they belong "
            "in manualSchemas as well: " + ", ".join(dangling)
        )


def _name_mappings(surface: dict) -> dict[str, str]:
    """Flatten per-schema field aliases into OpenAPI Generator name mappings.

    OpenAPI Generator only renames properties specification-wide, so two schemas may
    not map the same wire name to different Python attribute names.
    """
    mappings: dict[str, str] = {}
    for aliases in surface.get("fieldAliases", {}).values():
        for wire_name, attribute in aliases.items():
            conflict = mappings.get(wire_name)
            if conflict is not None and conflict != attribute:
                raise ValueError(
                    f"field alias for {wire_name} conflicts: {conflict} and {attribute}"
                )
            mappings[wire_name] = attribute
    return mappings


def _operation_roots(fragments: Iterable[Fragment]) -> dict[str, set[str]]:
    """Return the type names operations accept and return, keyed by manifest key."""
    roots: dict[str, set[str]] = {key: set() for _, key in CATEGORY_KEYS}
    for fragment in fragments:
        if fragment.kind != "operations":
            continue
        for route in json.loads(fragment.body):
            for key, field in (
                ("requests", "requestTypes"),
                ("responses", "responseTypes"),
            ):
                for data_type in route.get(field, []):
                    roots[key].update(TYPE_NAME.findall(data_type))
    return roots


def _reachable(
    roots: Iterable[str], references: dict[str, tuple[str, ...]]
) -> set[str]:
    """Return the declarations ``roots`` name, directly or through other declarations."""
    reached: set[str] = set()
    pending = [name for name in roots if name in references]
    while pending:
        name = pending.pop()
        if name in reached:
            continue
        reached.add(name)
        pending.extend(ref for ref in references[name] if ref in references)
    return reached


def schema_usage(fragments: list[Fragment]) -> dict[str, list[str]]:
    """Map every declaration to the manifest keys whose operations reach it.

    Parameters and request bodies reach ``requests``; responses of any status reach
    ``responses``. A declaration only webhooks or streams use maps to an empty list.
    """
    references = {
        fragment.name: fragment.references
        for fragment in fragments
        if fragment.kind != "operations"
    }
    reached = {
        key: _reachable(roots, references)
        for key, roots in _operation_roots(fragments).items()
    }
    return {
        name: [key for _, key in CATEGORY_KEYS if name in reached[key]]
        for name in references
    }


def _insert_sorted(names: list[str], additions: Iterable[str]) -> list[str]:
    """Insert ``additions`` where a case-insensitive sort puts them, moving nothing else.

    Some manifest lists are only roughly sorted, so re-sorting them would bury the
    additions in unrelated reordering.
    """
    merged = list(names)
    for name in _sorted_ignoring_case(additions):
        key = (name.casefold(), name)
        index = next(
            (
                position
                for position, existing in enumerate(merged)
                if (existing.casefold(), existing) > key
            ),
            len(merged),
        )
        merged.insert(index, name)
    return merged


def reconcile_manifest(
    fragments: list[Fragment], surface: dict
) -> tuple[dict, ManifestChanges]:
    """Classify new schemas by operation usage and prune schemas generation dropped.

    A schema only requests reach becomes a request and one only responses reach becomes
    a response. Existing entries are never moved, so earlier maintainer decisions stand.
    A schema both sides reach, or no operation reaches, stays unclassified so that
    ``_categorize`` rejects it.
    """
    usage = schema_usage(fragments)
    kinds = {fragment.name: fragment.kind for fragment in fragments}
    classified = {name for _, key in CATEGORY_KEYS for name in surface.get(key, [])}
    manual = set(surface.get("manualSchemas", []))

    added = {
        name: keys[0]
        for name, keys in usage.items()
        if kinds[name] != "enum"
        and name not in classified
        and name not in manual
        and len(keys) == 1
    }
    # A classified name that became an enum is still declared, so _categorize reports
    # the conflict instead of this silently dropping the entry.
    removed = {
        name: key
        for _, key in CATEGORY_KEYS
        for name in surface.get(key, [])
        if name not in usage
    }

    updated = dict(surface)
    for _, key in CATEGORY_KEYS:
        kept = [name for name in surface.get(key, []) if name not in removed]
        names = _insert_sorted(
            kept, (name for name, target in added.items() if target == key)
        )
        if key in surface or names:
            updated[key] = names
    return updated, ManifestChanges(added=added, removed=removed)


def write_manifest(surface: Path, document: dict) -> None:
    """Persist the ``requests`` and ``responses`` lists of ``document`` to the surface."""
    path = surface / "manifest.json" if surface.is_dir() else surface
    manifest = json.loads(path.read_text())
    for _, key in CATEGORY_KEYS:
        if key in document:
            manifest[key] = document[key]
    path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n")


def _describe_usage(keys: list[str]) -> str:
    if not keys:
        return "no operation uses it"
    return "used by " + " and ".join(keys)


def _categorize(fragments: list[Fragment], surface: dict) -> dict[str, str]:
    """Assign every generated declaration to exactly one category.

    ``manualSchemas`` is an exclusion list, so it may name declarations the current
    specification does not produce. Every other classification must match generated
    output, which is what turns an upstream rename into a generation failure.
    """
    declared: dict[str, str] = {}
    for category, key in CATEGORY_KEYS:
        for name in surface.get(key, []):
            if name in declared:
                raise ValueError(
                    f"{name} is classified as both {declared[name]} and {category}"
                )
            declared[name] = category
    manual = set(surface.get("manualSchemas", []))
    overlap = sorted(manual & set(declared))
    if overlap:
        raise ValueError(
            "manualSchemas also classifies generated schemas: " + ", ".join(overlap)
        )

    categories: dict[str, str] = {}
    unclassified = []
    for fragment in fragments:
        if fragment.kind == "operations":
            continue
        if fragment.name in manual:
            categories[fragment.name] = "manual"
        elif fragment.kind == "enum":
            declared_category = declared.get(fragment.name)
            if declared_category is not None:
                raise ValueError(
                    f"{fragment.name} is an enum and cannot be a {declared_category}"
                )
            categories[fragment.name] = "enum"
        elif fragment.name in declared:
            categories[fragment.name] = declared[fragment.name]
        else:
            unclassified.append(fragment.name)

    if unclassified:
        usage = schema_usage(fragments)
        raise ValueError(
            "add these generated schemas to requests, responses or manualSchemas "
            "(`make generate-openapi` classifies the ones used by only one side): "
            + ", ".join(
                f"{name} ({_describe_usage(usage.get(name, []))})"
                for name in sorted(unclassified)
            )
        )
    stale = sorted(set(declared) - set(categories))
    if stale:
        raise ValueError(
            "these surface classifications no longer match generated schemas "
            "(`make generate-openapi` prunes them): " + ", ".join(stale)
        )
    for key in ("baseClasses", "fieldAliases"):
        unknown = sorted(set(surface.get(key, {})) - set(categories))
        if unknown:
            raise ValueError(f"{key} names unknown schemas: {', '.join(unknown)}")
    return categories


def _base_classes(
    categories: dict[str, str], surface: dict, aliases: Iterable[str] = ()
) -> dict[str, str]:
    """Resolve the alpaca-py base class of every generated class.

    ``aliases`` names the union declarations, which are assignments rather than classes.
    """
    alias_names = set(aliases)
    bases = {
        name: base
        for name, category in categories.items()
        if name not in alias_names and (base := DEFAULT_BASES.get(category))
    }
    for name, base in surface.get("baseClasses", {}).items():
        if name in alias_names:
            raise ValueError(f"baseClasses cannot apply to union {name}")
        if categories[name] not in DEFAULT_BASES:
            raise ValueError(
                f"baseClasses cannot apply to {categories[name]} schema {name}"
            )
        if base not in BASE_IMPORTS:
            raise ValueError(f"unsupported base class {base} for {name}")
        bases[name] = base
    return bases


def _sorted_ignoring_case(values: Iterable[str]) -> list[str]:
    """Order names the way `isort --profile black` does, so its run is a no-op."""
    return sorted(values, key=lambda value: (value.casefold(), value))


def _used_import_statements(statements: Iterable[str], body: str) -> list[str]:
    """Keep only the imported names the assembled module actually references."""
    grouped: dict[str, set[str]] = {}
    for statement in statements:
        module, separator, names = statement.partition(" import ")
        if not separator:
            raise ValueError(f"unsupported import statement {statement!r}")
        for item in names.split(", "):
            symbol, _, binding = item.partition(" as ")
            if re.search(rf"\b{re.escape(binding or symbol)}\b", body):
                grouped.setdefault(module, set()).add(item)
    return _import_sections(
        f"{module} import {', '.join(_sorted_ignoring_case(names))}"
        for module, names in grouped.items()
    )


def _import_sections(statements: Iterable[str]) -> list[str]:
    """Lay out import statements in standard library, third party, alpaca-py order.

    The assembler owns every import it emits, so grouping them here keeps generation
    independent of an import sorter.
    """
    sections: dict[int, list[str]] = {}
    for statement in statements:
        root = (
            statement.removeprefix("from ").partition(" import ")[0].partition(".")[0]
        )
        if root in sys.stdlib_module_names:
            rank = 0
        elif root == FIRST_PARTY_PACKAGE:
            rank = 2
        else:
            rank = 1
        sections.setdefault(rank, []).append(statement)

    lines: list[str] = []
    for rank in sorted(sections):
        if lines:
            lines.append("")
        lines.extend(_sorted_ignoring_case(sections[rank]))
    return lines


def _declaration(fragment: Fragment, base: str) -> str:
    if fragment.kind == "union":
        return f"{fragment.name} = {fragment.body}"
    inherits = f"{fragment.enum_type}, Enum" if fragment.kind == "enum" else base
    return f"class {fragment.name}({inherits}):\n{fragment.body}"


def _union_members(fragment: Fragment) -> list[str]:
    """Return the names a ``Union[...]`` alias body composes."""
    return fragment.body[len("Union[") : -1].split(", ")


def _ordered_declarations(fragments: list[Fragment]) -> list[Fragment]:
    """Order declarations so every name is bound before it is used.

    Classes come first because union aliases are assignments evaluated at import
    time. Aliases are then emitted in dependency order, since a union that composes
    another union has to follow it.
    """
    classes = sorted(
        (fragment for fragment in fragments if fragment.kind != "union"),
        key=lambda fragment: fragment.name,
    )
    unions = {
        fragment.name: fragment for fragment in fragments if fragment.kind == "union"
    }

    ordered: list[Fragment] = []
    placed: set[str] = set()
    visiting: set[str] = set()

    def place(name: str) -> None:
        if name in placed:
            return
        if name in visiting:
            raise ValueError(f"union aliases form a cycle through {name}")
        visiting.add(name)
        for member in _union_members(unions[name]):
            if member in unions:
                place(member)
        visiting.discard(name)
        placed.add(name)
        ordered.append(unions[name])

    # Iterate sorted so the emitted order stays stable between runs.
    for name in sorted(unions):
        place(name)
    return classes + ordered


def _render_module(
    module: str,
    fragments: list[Fragment],
    bases: dict[str, str],
    modules_by_name: dict[str, str],
) -> str:
    declarations = _ordered_declarations(fragments)
    body = "\n\n\n".join(
        _declaration(fragment, bases.get(fragment.name, ""))
        for fragment in declarations
    )

    statements = {
        statement for fragment in declarations for statement in fragment.imports
    }
    position = {fragment.name: index for index, fragment in enumerate(declarations)}
    deferred: dict[str, str] = {}
    rebuild: set[str] = set()
    local_references: dict[str, list[str]] = {}
    for fragment in declarations:
        if fragment.kind == "enum":
            statements.add("from enum import Enum")
        elif fragment.kind != "union":
            statements.add(BASE_IMPORTS[bases[fragment.name]])
        for reference in fragment.references:
            target = modules_by_name.get(reference)
            if target == module:
                if fragment.kind in {"enum", "union"}:
                    continue
                local_references.setdefault(fragment.name, []).append(reference)
                # A model that names a later declaration of its own module (union
                # aliases always come after the classes) stays incomplete until it is
                # rebuilt once that name is bound.
                if position.get(reference, -1) > position[fragment.name]:
                    rebuild.add(fragment.name)
                continue
            if target is None:
                continue
            statement = f"from {fragment.package}.{target} import {reference}"
            if MODULE_LAYERS.index(target) > MODULE_LAYERS.index(module):
                if fragment.kind == "union":
                    # A union alias is evaluated at import time, but a name from a
                    # module that imports this one is only bound after the body, so
                    # the assignment would raise NameError and break the package.
                    raise ValueError(
                        f"union {fragment.name} in {module} cannot include {reference}, "
                        f"which is generated into {target}: {target} imports {module}, "
                        "so the member is not bound when the alias is evaluated "
                        f"(classify {reference} so it lands in {module} or earlier, "
                        "or add it to manualSchemas)"
                    )
                deferred[reference] = statement
                if fragment.kind != "enum":
                    rebuild.add(fragment.name)
            else:
                statements.add(statement)

    header = "\n".join(
        [
            BANNER,
            f'"""{MODULE_DOCSTRINGS[module]}"""',
            "",
            "from __future__ import annotations",
            "",
            *_used_import_statements(statements, body),
        ]
    )
    rebuild_order = _rebuild_order(rebuild, local_references)
    return f"{header}\n\n\n{body}\n{_deferred_bindings(deferred, rebuild_order)}"


def _rebuild_order(
    rebuild: set[str], local_references: dict[str, list[str]]
) -> list[str]:
    """Return every model needing a rebuild, dependencies first.

    A model that references an incomplete model of the same module is incomplete
    too, even when that model is declared earlier, so the set is closed over local
    references before ordering.
    """
    pending = set(rebuild)
    changed = True
    while changed:
        changed = False
        for name, references in local_references.items():
            if name not in pending and any(ref in pending for ref in references):
                pending.add(name)
                changed = True

    ordered: list[str] = []
    visited: set[str] = set()

    def visit(name: str) -> None:
        if name in visited:
            return
        visited.add(name)
        for reference in sorted(local_references.get(name, ())):
            if reference in pending and reference != name:
                visit(reference)
        ordered.append(name)

    for name in sorted(pending):
        visit(name)
    return ordered


def _deferred_bindings(deferred: dict[str, str], rebuild: list[str]) -> str:
    """Bind names from modules that import this one, then rebuild forward references.

    ``from __future__ import annotations`` keeps the field annotations lazy, so the
    models only need these names resolvable by the time they are rebuilt. Rebuilding
    at import keeps every model complete, so ``model_fields`` shows resolved types.
    """
    if not deferred and not rebuild:
        return ""
    lines: list[str] = []
    if deferred:
        lines += [
            "",
            "",
            "# Bound here rather than at the top because these names live in a module that",
            "# imports this one; importing them earlier would not resolve.",
            *_import_sections(
                f"{module} import {', '.join(_sorted_ignoring_case(names))}"
                for module, names in sorted(_grouped_imports(deferred.values()).items())
            ),
        ]
    if rebuild:
        lines += ["", ""] if not deferred else [""]
        lines.extend(f"{name}.model_rebuild()" for name in rebuild)
    return "\n".join(lines) + "\n"


def _grouped_imports(statements: Iterable[str]) -> dict[str, set[str]]:
    """Group ``from X import Y`` statements by their source module."""
    grouped: dict[str, set[str]] = {}
    for statement in statements:
        module, separator, names = statement.partition(" import ")
        if not separator:
            raise ValueError(f"unsupported import statement {statement!r}")
        grouped.setdefault(module, set()).update(names.split(", "))
    return grouped


def _render_package_init(package: str, modules_by_name: dict[str, str]) -> str:
    names_by_module: dict[str, list[str]] = {}
    for name, module in modules_by_name.items():
        names_by_module.setdefault(module, []).append(name)
    imports = [
        f"from {package}.{module} import {', '.join(_sorted_ignoring_case(names))}"
        for module, names in sorted(names_by_module.items())
    ]
    return "\n".join(
        [
            BANNER,
            '"""Generated bindings for the official Alpaca OpenAPI specification."""',
            "",
            *imports,
            "",
            "__all__ = [",
            *(f'    "{name}",' for name in sorted(modules_by_name)),
            "]",
            "",
        ]
    )


def _render_operations(document: dict, fragments: list[Fragment], surface: dict) -> str:
    """Resolve generated routes back to specification operation ids and method names."""
    methods = surface.get("operationMethods", {})
    operation_ids = {}
    for path, path_item in document.get("paths", {}).items():
        for method, operation in path_item.items():
            if method not in HTTP_METHODS:
                continue
            operation_id = operation.get("operationId")
            if not operation_id:
                raise ValueError(f"{method.upper()} {path} has no operationId")
            operation_ids[(path, method.upper())] = operation_id
    unmatched = sorted(set(methods) - set(operation_ids.values()))
    if unmatched:
        raise ValueError(
            "operationMethods names unknown operations: " + ", ".join(unmatched)
        )

    operations = []
    seen_routes: set[tuple[str, str]] = set()
    for fragment in fragments:
        for route in json.loads(fragment.body):
            key = (route["path"], route["httpMethod"])
            # OpenAPI Generator can emit the same path+method more than once
            # (for example multiple content types). Keep one entry per route.
            if key in seen_routes:
                continue
            seen_routes.add(key)
            if key not in operation_ids:
                raise ValueError(
                    f"generated route {key} is absent from the specification"
                )
            operation_id = operation_ids[key]
            operations.append(
                {
                    "operationId": operation_id,
                    "httpMethod": route["httpMethod"],
                    "path": route["path"],
                    "methodName": methods.get(operation_id),
                }
            )

    repeated = sorted(
        operation_id
        for operation_id, count in Counter(
            operation["operationId"] for operation in operations
        ).items()
        if count > 1
    )
    if repeated:
        raise ValueError("specification repeats operationIds: " + ", ".join(repeated))
    operations.sort(key=lambda operation: (operation["path"], operation["httpMethod"]))
    document = {"generatedBy": BANNER_SOURCE, "operations": operations}
    return json.dumps(document, indent=2, sort_keys=True) + "\n"


def require_formatter() -> None:
    """Fail before generating when the formatter this repository pins is missing.

    Generated code has to be formatted by the pinned version, otherwise every other
    maintainer sees `make check-openapi` report drift.
    """
    if importlib.util.find_spec(FORMATTER) is None:
        raise ToolchainError(
            f"{FORMATTER} is not installed in {sys.executable}; run `poetry install` "
            "to install the development dependencies"
        )


def _format_python(directory: Path) -> None:
    """Wrap the long lines the templates emit, matching `make lint`."""
    _run([sys.executable, "-m", FORMATTER, str(directory)])


def _publish(assembled: Path, output: Path) -> None:
    """Replace ``output`` with ``assembled`` without leaving it partially written."""
    output.parent.mkdir(parents=True, exist_ok=True)
    staging = output.parent / f".{output.name}.staging"
    previous = output.parent / f".{output.name}.previous"
    for scratch in (staging, previous):
        shutil.rmtree(scratch, ignore_errors=True)

    shutil.copytree(assembled, staging)
    if output.exists():
        output.replace(previous)
    try:
        staging.replace(output)
    except OSError:
        if previous.exists():
            previous.replace(output)
        raise
    finally:
        shutil.rmtree(staging, ignore_errors=True)
        shutil.rmtree(previous, ignore_errors=True)


def dotted_name(path: Path, root: Path = REPOSITORY_ROOT) -> str:
    """Return the import name of a module file or package directory under ``root``."""
    relative = path.relative_to(root)
    if relative.suffix == ".py":
        relative = relative.with_suffix("")
        if relative.name == "__init__":
            relative = relative.parent
    return ".".join(relative.parts)


def declared_names(module: Path) -> set[str]:
    """Return the classes and aliases a generated module declares.

    This matches what the generated-compatibility tests require each public module to
    bind, so deferred imports and ``model_rebuild()`` calls do not count.
    """
    names: set[str] = set()
    for node in ast.parse(module.read_text()).body:
        if isinstance(node, ast.ClassDef):
            names.add(node.name)
        elif isinstance(node, ast.Assign):
            names.update(
                target.id for target in node.targets if isinstance(target, ast.Name)
            )
    return names


def _generated_imports(tree: ast.Module, module: str) -> list[ast.ImportFrom]:
    return [
        node
        for node in tree.body
        if isinstance(node, ast.ImportFrom)
        and node.level == 0
        and node.module == module
    ]


def dropped_reexports(public: Path, module: str, declared: set[str]) -> list[str]:
    """Return the names ``public`` imports from ``module`` that it no longer declares."""
    tree = ast.parse(public.read_text())
    return sorted(
        alias.name
        for node in _generated_imports(tree, module)
        for alias in node.names
        if alias.name != "*" and alias.name not in declared
    )


def bound_names(modules: Iterable[str], root: Path = REPOSITORY_ROOT) -> dict:
    """Import ``modules`` from ``root`` in a fresh interpreter and list their names."""
    try:
        completed = subprocess.run(
            [sys.executable, "-c", _BOUND_NAMES, *sorted(modules)],
            check=True,
            cwd=root,
            capture_output=True,
            text=True,
        )
    except subprocess.CalledProcessError as error:
        raise ValueError(
            "cannot import the public modules to check their re-exports:\n"
            + error.stderr.strip()
        ) from error
    bound = json.loads(completed.stdout.splitlines()[-1])
    return {name: set(names) for name, names in bound.items()}


def _fill_rows(
    names: list[str], width: int, original: Sequence[list[str]] = ()
) -> list[list[str]]:
    """Pack names into ``    A, B,`` rows no wider than ``width``.

    Once the names left over match the tail of ``original`` row for row, those rows
    are kept as they are, so an insertion only reflows the rows it has to.
    """
    tails = {
        tuple(name for row in original[index:] for name in row): index
        for index in range(len(original))
    }
    rows: list[list[str]] = []
    position = 0
    while position < len(names):
        tail = tails.get(tuple(names[position:]))
        if tail is not None:
            return rows + [list(row) for row in original[tail:]]
        row = [names[position]]
        position += 1
        while (
            position < len(names)
            and len(f"    {', '.join(row + [names[position]])},") <= width
        ):
            row.append(names[position])
            position += 1
        rows.append(row)
    return rows


def add_reexports(public: Path, module: str, names: Iterable[str]) -> None:
    """Insert ``names`` into the parenthesized block that imports from ``module``.

    Rows before the first insertion stay untouched. Blocks that pack several names per
    row are refilled from that point on at their existing width, and one-name-per-row
    blocks just gain rows.
    """
    additions = list(names)
    source = public.read_text()
    blocks = [
        node
        for node in _generated_imports(ast.parse(source), module)
        if node.end_lineno > node.lineno
        and all(alias.asname is None for alias in node.names)
    ]
    if not blocks:
        raise ValueError(
            f"{public} has no parenthesized import from {module}, so add these "
            "re-exports by hand: " + ", ".join(additions)
        )
    block = max(blocks, key=lambda node: len(node.names))
    lines = source.splitlines(keepends=True)
    # Black closes the block on a line of its own after a trailing comma; isort's grid
    # layout closes it right after the last name.
    closing = lines[block.end_lineno - 1].strip()
    inline_close = closing != ")"
    inner = lines[
        block.lineno : block.end_lineno if inline_close else block.end_lineno - 1
    ]
    rows = [
        [name.strip() for name in line.strip().rstrip(",)").split(",")]
        for line in inner
    ]
    existing = [name for row in rows for name in row]
    if (
        not lines[block.lineno - 1].rstrip().endswith("(")
        or not closing.endswith(")")
        or existing != [alias.name for alias in block.names]
    ):
        raise ValueError(
            f"the import from {module} in {public} has a layout generation cannot "
            "edit, so add these re-exports by hand: " + ", ".join(additions)
        )

    merged = _insert_sorted(existing, additions)
    first_change = next(
        index
        for index, (new, old) in enumerate(zip(merged, existing + [""]))
        if new != old
    )
    kept: list[list[str]] = []
    count = 0
    for row in rows:
        if count + len(row) >= first_change:
            break
        kept.append(row)
        count += len(row)
    rest = merged[count:]
    if any(len(row) > 1 for row in rows):
        width = max(len(line.rstrip("\n")) for line in inner)
        refilled = _fill_rows(rest, width, rows[len(kept) :])
    else:
        refilled = [[name] for name in rest]
    rendered = [f"    {', '.join(row)},\n" for row in kept + refilled]
    if inline_close:
        rendered[-1] = rendered[-1].replace(",\n", ")\n")
    lines[block.lineno : block.lineno + len(inner)] = rendered
    public.write_text("".join(lines))


def _describe_reexports(problems: dict[Path, list[str]], root: Path) -> str:
    return "; ".join(
        f"{path.relative_to(root) if path.is_relative_to(root) else path}: "
        + ", ".join(names)
        for path, names in sorted(problems.items())
    )


def reject_dropped_reexports(
    public: dict[str, Path],
    package: str,
    generated: Path,
    root: Path = REPOSITORY_ROOT,
) -> None:
    """Fail when a public module re-exports a name ``generated`` no longer declares."""
    dropped = {
        path: names
        for key, path in public.items()
        if (
            names := dropped_reexports(
                path, f"{package}.{key}", declared_names(generated / f"{key}.py")
            )
        )
    }
    if dropped:
        raise ValueError(
            "public modules re-export names the specification dropped; removing a "
            "public name breaks users, so delete each import or replace it with a "
            "hand-written definition: " + _describe_reexports(dropped, root)
        )


def missing_reexports(
    public: dict[str, Path],
    generated: Path,
    root: Path = REPOSITORY_ROOT,
) -> dict[Path, list[str]]:
    """Return the names ``generated`` declares that each public module does not bind.

    A hand-written override of a generated name counts as bound, so only names absent
    from the public module are reported.
    """
    modules = {key: dotted_name(path, root) for key, path in public.items()}
    bound = bound_names(modules.values(), root)
    missing = {
        path: sorted(
            declared_names(generated / f"{key}.py") - bound[modules[key]],
            key=lambda name: (name.casefold(), name),
        )
        for key, path in public.items()
    }
    return {path: names for path, names in missing.items() if names}


def generate(
    spec: Path,
    output: Path,
    surface: Path,
    generator: Path | None = None,
    update_sources: bool = False,
    public: dict[str, Path] | None = None,
) -> GenerationReport:
    """Generate the modules described by ``spec`` into ``output``.

    ``public`` maps each generated module (``enums``, ``models``, ``requests``) to the
    hand-written module that re-exports it. ``output`` must then be the package those
    modules import from. A dropped re-export fails before anything is written.

    With ``update_sources`` the surface manifest gains the schemas operation usage
    classifies and loses the ones generation no longer produces, and public modules
    gain the generated names they lack. Both are written only after the generated
    package is published. Without it, missing re-exports fail generation.
    """
    require_formatter()
    surface_document = load_surface(surface)
    document = json.loads(spec.read_text())
    generation_document = apply_spec_patches(
        document, surface_document.get("specPatches")
    )
    generator_config = generator or PYTHON_CONFIG

    with tempfile.TemporaryDirectory(prefix="alpaca-openapi-") as workspace:
        sandbox = Path(workspace)
        patched_spec = sandbox / "input-spec.json"
        patched_spec.write_text(
            json.dumps(generation_document, indent=2, ensure_ascii=False) + "\n"
        )
        _run_generator(
            patched_spec,
            generator_config,
            sandbox / "generated",
            _name_mappings(surface_document),
        )

        fragments = apply_schema_docstrings(
            _read_fragments(sandbox / "generated"),
            _schema_descriptions(document),
        )
        reject_unsupported_fragments(
            fragments, set(surface_document.get("manualSchemas", []))
        )
        packages = {fragment.package for fragment in fragments}
        if len(packages) != 1:
            raise ValueError(
                f"expected exactly one generated package, found {packages}"
            )
        package = packages.pop()

        changes = ManifestChanges(added={}, removed={})
        if update_sources:
            surface_document, changes = reconcile_manifest(fragments, surface_document)
        categories = _categorize(fragments, surface_document)
        reject_manual_references(fragments, categories)
        bases = _base_classes(
            categories,
            surface_document,
            [fragment.name for fragment in fragments if fragment.kind == "union"],
        )

        by_module: dict[str, list[Fragment]] = {}
        routes = []
        for fragment in fragments:
            if fragment.kind == "operations":
                routes.append(fragment)
            elif categories[fragment.name] != "manual":
                module = CATEGORY_MODULES[categories[fragment.name]]
                by_module.setdefault(module, []).append(fragment)

        modules_by_name = {
            fragment.name: module
            for module, module_fragments in by_module.items()
            for fragment in module_fragments
        }

        assembled = sandbox / "assembled"
        assembled.mkdir()
        for module in sorted(CATEGORY_MODULES.values()):
            (assembled / f"{module}.py").write_text(
                _render_module(
                    module, by_module.get(module, []), bases, modules_by_name
                )
            )
        (assembled / "__init__.py").write_text(
            _render_package_init(package, modules_by_name)
        )
        _format_python(assembled)
        (assembled / "operations.json").write_text(
            _render_operations(document, routes, surface_document)
        )
        if public:
            reject_dropped_reexports(public, package, assembled)
        _publish(assembled, output)
    if changes:
        write_manifest(surface, surface_document)

    missing = missing_reexports(public, output) if public else {}
    if missing and not update_sources:
        raise ValueError(
            "public modules do not re-export these generated names: "
            + _describe_reexports(missing, REPOSITORY_ROOT)
        )
    for key, path in (public or {}).items():
        if path in missing:
            add_reexports(path, f"{package}.{key}", missing[path])
    return GenerationReport(manifest=changes, reexports=missing)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("target", choices=TARGETS)
    parser.add_argument(
        "--output", type=Path, help="override the generated package location"
    )
    parser.add_argument(
        "--update-sources",
        action=argparse.BooleanOptionalAction,
        default=True,
        help="classify new schemas in the surface manifest, prune dropped ones and "
        "add new generated names to the public modules",
    )
    args = parser.parse_args()

    target = TARGETS[args.target]
    output = args.output or target["output"]
    try:
        report = generate(
            spec=target["spec"],
            output=output,
            surface=target["surface"],
            generator=target.get("generator"),
            update_sources=args.update_sources,
            # Public modules import the checked-in package, so an override output
            # leaves nothing for them to be checked against.
            public=None if args.output else target["public"],
        )
    except ToolchainError as error:
        # A missing tool is a setup problem, so report it without a traceback.
        print(error, file=sys.stderr)
        return 1
    if report.manifest:
        manifest = target["surface"] / "manifest.json"
        print(f"Updated {manifest.relative_to(REPOSITORY_ROOT)}; review these entries:")
        print("\n".join(report.manifest.describe()))
    for path, names in sorted(report.reexports.items()):
        print(f"Updated {path.relative_to(REPOSITORY_ROOT)}; review these re-exports:")
        print("\n".join(f"  + {name}" for name in names))
    print(f"Generated: {output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
