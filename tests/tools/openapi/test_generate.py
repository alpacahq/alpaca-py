def _fragment(
    name: str,
    *,
    kind: str = "model",
    body: str = "",
    references: tuple[str, ...] = (),
) -> generate.Fragment:
    return generate.Fragment(
        kind=kind,
        name=name,
        enum_type="",
        package="alpaca.trading._generated",
        references=references,
        imports=(),
        body=body,
    )


