def test_apply_schema_docstrings_rewrites_flattened_generator_text():
    fragment = _fragment(
        "OrderStatus",
        kind="enum",
        body=(
            '    """\n'
            "    The status of an order.   Supported values:   - `new`: accepted\n"
            '    """\n'
            "\n"
            '    NEW = "new"\n'
        ),
    )

    restored = generate.apply_schema_docstrings(
        [fragment],
        {
            "OrderStatus": (
                "The status of an order.\n\nSupported values:\n- `new`: accepted"
            )
        },
    )[0]

    assert restored.body.startswith(
        '    """\n'
        "    The status of an order.\n"
        "\n"
        "    Supported values:\n"
        "\n"
        "    - `new`: accepted\n"
        '    """\n'
    )
    assert 'NEW = "new"' in restored.body


