@requires_generator
def test_generation_classifies_new_schemas_in_the_manifest(tmp_path):
    surface = tmp_path / "surface"
    surface.mkdir()
    documents = json.loads(json.dumps(FIXTURE_SURFACE))
    documents["manifest.json"]["responses"] = ["OrderLike", "OrderPreview", "Removed"]
    for name, document in documents.items():
        (surface / name).write_text(json.dumps(document, indent=2) + "\n")

    with pytest.raises(ValueError, match=r"Order \(used by responses\)"):
        generate.generate(
            spec=FIXTURE_SPEC, output=tmp_path / "checked", surface=surface
        )
    report = generate.generate(
        spec=FIXTURE_SPEC,
        output=tmp_path / "_generated",
        surface=surface,
        update_sources=True,
    )

    assert report.manifest.added == {"Order": "responses"}
    assert report.manifest.removed == {"Removed": "responses"}
    assert report.reexports == {}
    manifest = json.loads((surface / "manifest.json").read_text())
    assert manifest == FIXTURE_SURFACE["manifest.json"]


