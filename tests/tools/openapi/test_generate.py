def test_apply_spec_patches_rewrites_a_leaf_value():
    document = {
        "components": {
            "schemas": {
                "OrderLeg": {
                    "properties": {
                        "legs": {
                            "type": "null",
                            "items": {"type": "object"},
                        }
                    }
                }
            }
        }
    }

    patched = generate.apply_spec_patches(
        document,
        [
            {
                "path": [
                    "components",
                    "schemas",
                    "OrderLeg",
                    "properties",
                    "legs",
                    "type",
                ],
                "value": ["array", "null"],
                "reason": "openapi-generator cannot map type:null",
            }
        ],
    )

    assert patched["components"]["schemas"]["OrderLeg"]["properties"]["legs"][
        "type"
    ] == ["array", "null"]
    # The input document must stay a faithful copy of the pinned download.
    assert (
        document["components"]["schemas"]["OrderLeg"]["properties"]["legs"]["type"]
        == "null"
    )


