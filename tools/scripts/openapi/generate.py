class ToolchainError(RuntimeError):
    """A tool this script shells out to is missing from the environment."""


@dataclass(frozen=True)
class Fragment:
    """A generated class body awaiting a class statement and a home module."""

    kind: str
    name: str
    enum_type: str
    package: str
    references: tuple[str, ...]
    imports: tuple[str, ...]
    body: str


@dataclass(frozen=True)
class ManifestChanges:
    """Manifest entries generation added or pruned, keyed by schema name."""

    added: dict[str, str]
    removed: dict[str, str]

    def __bool__(self) -> bool:
        return bool(self.added or self.removed)

    def describe(self) -> list[str]:
        lines = [f"  + {key}: {name}" for name, key in sorted(self.added.items())]
        lines += [f"  - {key}: {name}" for name, key in sorted(self.removed.items())]
        return lines


@dataclass(frozen=True)
class GenerationReport:
    """Hand-maintained files generation edited, for the maintainer to review."""

    manifest: ManifestChanges
    reexports: dict[Path, list[str]]

    def __bool__(self) -> bool:
        return bool(self.manifest or self.reexports)


