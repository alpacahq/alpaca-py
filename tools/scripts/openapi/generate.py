"""Generate alpaca-py source modules from a pinned OpenAPI specification.

OpenAPI Generator runs in a temporary directory with repository-owned templates that
emit class bodies instead of standalone modules. This script then writes the class
statements and combines the fragments into one module per category, so the public SDK
layout, base classes and module names stay hand-designed and stable.

Each API surface under ``tools/openapi/surfaces/<name>/`` declares:

- ``manifest.json`` — schema classification (``requests``, ``responses``, ``manualSchemas``)
- ``sdk.json`` — SDK shaping (``baseClasses``, ``fieldAliases``, operation maps)
- ``patches.json`` — optional ``specPatches`` applied to a deep copy of the pinned spec

When the specification adds a schema that only operation requests or only operation
responses reach, ``make generate-openapi`` classifies it in ``manifest.json`` and reports
it for review. Schemas the specification drops are pruned the same way. A schema both
sides reach, or no operation reaches, still fails generation until a maintainer
classifies it.

Public modules such as ``alpaca/broker/models/__init__.py`` re-export generated names
through an explicit import block. Generation adds new names to that block and reports
them. A re-export of a name the specification dropped fails generation before anything
is written, because removing a public name is a maintainer's call.
``make check-openapi`` reports both cases and never edits files.
"""

