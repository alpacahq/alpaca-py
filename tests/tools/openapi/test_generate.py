def _operations(*routes: dict) -> generate.Fragment:
    return _fragment("OrdersApi", kind="operations", body=json.dumps(list(routes)))


def _manifest_fragments() -> list[generate.Fragment]:
    return [
        _operations(
            {
                "httpMethod": "POST",
                "path": "/v2/orders",
                "requestTypes": ["PlaceOrderRequest"],
                "responseTypes": ["Order", "UnexpectedErrorLike"],
            },
            {
                "httpMethod": "PATCH",
                "path": "/v2/orders",
                "requestTypes": ["List[Leg]"],
                "responseTypes": ["Dict[str, Leg]"],
            },
        ),
        _fragment("PlaceOrderRequest", references=("Leg", "OrderSide")),
        _fragment("Order", references=("Leg",)),
        _fragment("Leg"),
        _fragment("OrderSide", kind="enum"),
        _fragment(
            "UnexpectedErrorLike",
            kind="union",
            body="Union[Error, UnexpectedError]",
            references=("Error", "UnexpectedError"),
        ),
        _fragment("Error"),
        _fragment("UnexpectedError"),
        _fragment("WebhookEvent"),
    ]


def test_schema_usage_follows_operations_through_references_and_containers():
    usage = generate.schema_usage(_manifest_fragments())

    assert usage["PlaceOrderRequest"] == ["requests"]
    assert usage["UnexpectedError"] == ["responses"]
    assert usage["Leg"] == ["requests", "responses"]
    assert usage["WebhookEvent"] == []


def test_reconcile_manifest_classifies_one_sided_schemas_and_prunes_dropped_ones():
    surface = {
        "requests": ["PlaceOrderRequest", "RemovedRequest"],
        "responses": ["Order", "Leg", "Error"],
        "manualSchemas": ["WebhookEvent"],
    }

    updated, changes = generate.reconcile_manifest(_manifest_fragments(), surface)

    assert changes.added == {
        "UnexpectedError": "responses",
        "UnexpectedErrorLike": "responses",
    }
    assert changes.removed == {"RemovedRequest": "requests"}
    assert updated["requests"] == ["PlaceOrderRequest"]
    assert updated["responses"] == [
        "Order",
        "Leg",
        "Error",
        "UnexpectedError",
        "UnexpectedErrorLike",
    ]
    assert surface["requests"] == ["PlaceOrderRequest", "RemovedRequest"]


def test_reconcile_manifest_leaves_ambiguous_schemas_for_categorize_to_reject():
    surface = {"requests": ["PlaceOrderRequest"], "responses": ["Order"]}

    updated, changes = generate.reconcile_manifest(_manifest_fragments(), surface)

    assert "Leg" not in changes.added
    assert "WebhookEvent" not in changes.added
    with pytest.raises(ValueError) as error:
        generate._categorize(_manifest_fragments(), updated)
    message = str(error.value)
    assert "Leg (used by requests and responses)" in message
    assert "WebhookEvent (no operation uses it)" in message


