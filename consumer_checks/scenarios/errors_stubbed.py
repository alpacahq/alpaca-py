"""Retries and error mapping, against fixed responses.

The API cannot be made to return 429, 5xx or a non-JSON body on demand, so
these scenarios serve fixed responses (``stub_responses``) instead of calling
it, in every mode. Recording still runs them with the BASELINE release, so the
requests the SDK sends (including how many times it retries) and the errors it
raises are frozen like any other scenario. An autogenerated HTTP layer is
where retry counts and error mapping most easily change.
"""

from __future__ import annotations

from typing import Any, Dict

from alpaca.common.exceptions import APIError
from alpaca.trading.models import Clock

from . import Context, scenario
from ._errors import error_details

CLOCK = {
    "timestamp": "2024-03-04T10:00:00-05:00",
    "is_open": True,
    "next_open": "2024-03-05T09:30:00-05:00",
    "next_close": "2024-03-04T16:00:00-05:00",
}
RATE_LIMITED = {
    "status": 429,
    "json": {"code": 42910000, "message": "rate limit exceeded"},
}


@scenario(
    covers=["TradingClient.get_clock"],
    stub_responses=[RATE_LIMITED, {"status": 200, "json": CLOCK}],
)
def rate_limited_request_is_retried(ctx: Context) -> Dict[str, Any]:
    # Users never see the 429: the SDK retries and returns the result.
    clock = ctx.trading.get_clock()
    assert isinstance(clock, Clock)
    return {"clock": clock}


@scenario(
    covers=["TradingClient.get_clock"],
    stub_responses=[RATE_LIMITED] * 4,
)
def rate_limit_retries_run_out(ctx: Context) -> Dict[str, Any]:
    # 3 retries by default: the 4th 429 reaches the user.
    try:
        ctx.trading.get_clock()
    except APIError as error:
        assert error.status_code == 429
        return error_details(error)
    raise AssertionError("an exhausted retry should raise APIError")


@scenario(
    covers=["TradingClient.get_clock"],
    stub_responses=[
        {"status": 504, "text": "<html><body>504 Gateway Time-out</body></html>"},
        {"status": 200, "json": CLOCK},
    ],
)
def gateway_timeout_is_retried(ctx: Context) -> Dict[str, Any]:
    clock = ctx.trading.get_clock()
    assert isinstance(clock, Clock)
    return {"clock": clock}


@scenario(
    covers=["TradingClient.get_clock"],
    stub_responses=[
        {"status": 500, "json": {"code": 50010000, "message": "internal server error"}}
    ],
)
def server_error_is_not_retried(ctx: Context) -> Dict[str, Any]:
    try:
        ctx.trading.get_clock()
    except APIError as error:
        assert error.status_code == 500
        return error_details(error)
    raise AssertionError("a 500 should raise APIError")


@scenario(
    covers=["TradingClient.get_clock"],
    stub_responses=[
        {"status": 502, "text": "<html><body>502 Bad Gateway</body></html>"}
    ],
)
def non_json_error_body(ctx: Context) -> Dict[str, Any]:
    # A proxy error page, not API JSON. In 0.45.0, status_code works but
    # reading code or message raises.
    try:
        ctx.trading.get_clock()
    except APIError as error:
        assert error.status_code == 502
        return error_details(error)
    raise AssertionError("a 502 should raise APIError")
